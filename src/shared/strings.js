/** Safe nested lookup: t('el','order.errors.BAD_NAME'). Falls back to Greek, then to the key. */
export function t(lang, path) {
  const get = (l) => path.split('.').reduce((o, k) => (o == null ? o : o[k]), S[l]);
  return get(lang) ?? get(DEFAULT_LANG) ?? path;
}

/** Replace {name} tokens. */
export function fmt(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Localised field of a {el,en} object. */
export const L = (obj, lang) => (obj ? obj[lang] || obj.el : '');
