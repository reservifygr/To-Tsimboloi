export function deepMerge(base, extra) {
  for (const [k, v] of Object.entries(extra)) {
    if (v && typeof v === 'object' && !Array.isArray(v)) { base[k] = base[k] && typeof base[k] === 'object' ? base[k] : {}; deepMerge(base[k], v); } else base[k] = v;
  }
  return base;
}
